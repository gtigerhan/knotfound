"""Add arXiv papers to feed.js by reading arxiv.org pages directly (fallback when the arXiv API is rate-limited).
Run: python scripts/add_arxiv_pages.py
- IDS: known arXiv ids per topic (found earlier through OpenAlex)
- SEARCH: arxiv.org title searches per topic (first N results)
"""
import html, json, re, time, urllib.parse, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FEED = ROOT / "feed.js"
UA = {"User-Agent": "knotfound-feed/1.0 (educational hackathon project)"}

IDS = {
    "grid": ["2406.15361", "2012.14269", "2402.02717", "2407.15859", "2007.05711", "1106.2723", "1010.3005", "1010.2916",
             "2609.20900", "1704.01787", "2602.02642", "0710.0359", "0812.3665", "1010.3997", "2307.11212", "0907.5401"],
}
SEARCH = {
    "beginner": [("tricolorability", 4), ("Fox coloring", 4), ("stick number", 5), ("knot table", 3)],
}

def fetch(url):
    for i in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
                return r.read().decode("utf-8", "replace")
        except Exception as ex:
            if i == 3: raise
            time.sleep(5 * (i + 1))

def meta(page, name):
    return [html.unescape(m) for m in re.findall(rf'<meta name="{name}" content="([^"]*)"', page)]

def paper(aid):
    page = fetch(f"https://arxiv.org/abs/{aid}")
    title = (meta(page, "citation_title") or [""])[0]
    if not title: return None
    authors = []
    for a in meta(page, "citation_author")[:4]:
        last, _, first = a.partition(", ")
        authors.append((first + " " + last).strip())
    date = (meta(page, "citation_date") or ["2000"])[0]
    return {"id": "arxiv:" + aid, "kind": "paper", "src": "arXiv", "title": " ".join(title.split()),
            "authors": authors or ["Unknown"], "year": int(date[:4]),
            "abstract": " ".join((meta(page, "citation_abstract") or [""])[0].split())[:600],
            "embed": f"https://arxiv.org/pdf/{aid}", "url": f"https://arxiv.org/abs/{aid}"}

def search(q, n):
    url = "https://arxiv.org/search/?" + urllib.parse.urlencode({"query": q, "searchtype": "title", "size": 25, "order": ""})
    page = fetch(url)
    ids = []
    for m in re.findall(r'href="https://arxiv\.org/abs/([^"v]+(?:v\d+)?)"', page):
        aid = re.sub(r"v\d+$", "", m)
        if aid not in ids: ids.append(aid)
    return ids[:n]

src = FEED.read_text(encoding="utf-8")
topics = json.loads(re.search(r"const TOPICS = (\[.*?\]);", src, re.S).group(1))
docs = json.loads(re.search(r"const DOCS = (\[.*\]);", src, re.S).group(1))
seen = {d["id"]: d for d in docs}
plan = {t: list(ids) for t, ids in IDS.items()}
for t, qs in SEARCH.items():
    for q, n in qs:
        found = search(q, n); print(f"search {t}: '{q}' -> {found}")
        plan.setdefault(t, []).extend(found); time.sleep(3)
added = 0
for t, ids in plan.items():
    for aid in ids:
        did = "arxiv:" + aid
        if did in seen:
            if t not in seen[did]["topics"]: seen[did]["topics"].append(t)
            continue
        d = paper(aid); time.sleep(2)
        if not d: print("  skip", aid); continue
        d["topics"] = [t]; docs.append(d); seen[did] = d; added += 1
        print(f"  + [{t}] {d['year']} {d['title'][:70]}")
FEED.write_text("// generated by scripts/build_feed.py (+ scripts/add_arxiv_pages.py)\nconst TOPICS = " + json.dumps(topics, ensure_ascii=False) +
                ";\nconst DOCS = " + json.dumps(docs, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
print(added, "papers added,", len(docs), "docs total")
