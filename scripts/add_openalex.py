"""Add arXiv papers found through OpenAlex (used when the arXiv API is rate-limited) to feed.js.
Run: python scripts/add_openalex.py
Each entry below: topic id -> list of (search text, how many papers to keep).
"""
import json, re, time, urllib.error, urllib.parse, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FEED = ROOT / "feed.js"
UA = {"User-Agent": "knotfound-feed/1.0 (educational hackathon project)"}
ARXIV_SOURCE = "S4306400194"   # OpenAlex id of the arXiv repository

SEARCHES = {
    "grid": [("arc index grid diagram knot", 16), ("minimal grid diagram knot", 6), ("arc presentation knot", 4)],
    "beginner": [("tricolorability knot", 5), ("Fox coloring knot", 5), ("stick number knot", 6), ("knot table tabulation", 4)],
}

def get(url):
    for i in range(6):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
                return json.loads(r.read())
        except urllib.error.HTTPError as ex:
            if ex.code != 429 or i == 5: raise
            time.sleep(6 * (i + 1))

def abstract(inv):
    if not inv: return ""
    pos = sorted((p, w) for w, ps in inv.items() for p in ps)
    return " ".join(w for _, w in pos)

def tidy(title):
    title = " ".join(title.split())
    return title.title() if title.isupper() else title

src = FEED.read_text(encoding="utf-8")
topics = json.loads(re.search(r"const TOPICS = (\[.*?\]);", src, re.S).group(1))
docs = json.loads(re.search(r"const DOCS = (\[.*\]);", src, re.S).group(1))
seen = {d["id"]: d for d in docs}
added = 0
for tid, queries in SEARCHES.items():
    for q, keep in queries:
        url = "https://api.openalex.org/works?" + urllib.parse.urlencode({
            "search": q, "filter": f"locations.source.id:{ARXIV_SOURCE}", "per-page": 25,
            "select": "title,publication_year,authorships,locations,abstract_inverted_index"})
        got = 0
        for w in get(url)["results"]:
            if got >= keep: break
            ax = next((l["landing_page_url"] for l in w["locations"] if l.get("landing_page_url") and "arxiv.org/abs/" in l["landing_page_url"]), None)
            if not ax or not w.get("title"): continue
            aid = re.sub(r"v\d+$", "", ax.split("/abs/")[1])
            did = "arxiv:" + aid
            if did in seen:
                if tid not in seen[did]["topics"]: seen[did]["topics"].append(tid)
                got += 1; continue
            d = {"id": did, "kind": "paper", "src": "arXiv", "title": tidy(w["title"]),
                 "authors": [a["author"]["display_name"] for a in w["authorships"]][:4] or ["Unknown"],
                 "year": w["publication_year"], "abstract": abstract(w.get("abstract_inverted_index"))[:600],
                 "embed": f"https://arxiv.org/pdf/{aid}", "url": f"https://arxiv.org/abs/{aid}", "topics": [tid]}
            docs.append(d); seen[did] = d; got += 1; added += 1
        print(f"{tid}: '{q}' -> {got}")
        time.sleep(3)

FEED.write_text("// generated by scripts/build_feed.py (+ scripts/add_openalex.py)\nconst TOPICS = " + json.dumps(topics, ensure_ascii=False) +
                ";\nconst DOCS = " + json.dumps(docs, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
print(added, "papers added,", len(docs), "docs total")
