"""Document lengths -> meta.js. Papers: page count (from the PDFs cached by build_thumbs.py).
Articles: word count of the Wikipedia article. Run: python scripts/build_meta.py [pdf-cache-dir]"""
import json, re, sys, time, urllib.error, urllib.parse, urllib.request
from pathlib import Path
import pymupdf

ROOT = Path(__file__).resolve().parent.parent
CACHE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / ".pdfcache"
UA = {"User-Agent": "knotfound-meta/1.0 (educational hackathon project)"}
DOCS = json.loads(re.search(r"const DOCS = (\[.*\]);", (ROOT / "feed.js").read_text(encoding="utf-8"), re.S).group(1))
safe = lambda i: re.sub(r"[^A-Za-z0-9._-]", "_", i)

meta = {}
old = ROOT / "meta.js"
if old.exists():
    meta = json.loads(re.search(r"const META = (\{.*\});", old.read_text(encoding="utf-8"), re.S).group(1))
for d in DOCS:
    if d["id"] in meta: continue
    try:
        if d["kind"] == "paper":
            pdf = CACHE / (safe(d["id"].split(":", 1)[1]) + ".pdf")
            if pdf.exists(): meta[d["id"]] = {"pages": len(pymupdf.open(pdf))}
        else:
            title = d["url"].split("/wiki/")[1]
            req = urllib.request.Request(f"https://en.wikipedia.org/api/rest_v1/page/html/{title}", headers=UA)
            for i in range(5):
                try:
                    html = urllib.request.urlopen(req, timeout=40).read().decode("utf-8"); break
                except urllib.error.HTTPError as ex:
                    if ex.code != 429 or i == 4: raise
                    time.sleep(5 * (i + 1))
            text = re.sub(r"<(style|script)[^>]*>.*?</\1>|<[^>]+>", " ", html, flags=re.S)
            meta[d["id"]] = {"words": len(text.split())}
            time.sleep(1.0)
    except Exception as ex:
        print("fail", d["id"], ex)
(ROOT / "meta.js").write_text("// generated by scripts/build_meta.py\nconst META = " + json.dumps(meta) + ";\n", encoding="utf-8")
print(len(meta), "entries")
